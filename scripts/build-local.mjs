import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const read=name=>readFile(new URL(name,root),'utf8');
const core=(await read('public-core.js')).replace(/^export /gm,'');
let app=(await read('app.js')).replace(/^import .*\r?\n/,'');
const registry=JSON.parse(await read('cvm-companies.json'));
const catalog=JSON.parse(await read('catalog.json'));
app=app.replace("await fetch('./cvm-companies.json')","({ok:true,json:async()=>LOCAL_REGISTRY})")
 .replace("await fetch('./catalog.json')","({ok:true,json:async()=>LOCAL_CATALOG})");
await writeFile(new URL('local-app.js',root),`// Generated by node scripts/build-local.mjs. Do not edit directly.\n(async()=>{\nconst LOCAL_REGISTRY=${JSON.stringify(registry)};\nconst LOCAL_CATALOG=${JSON.stringify(catalog)};\n${core}\n${app}\n})();\n`);
